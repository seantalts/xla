// Also test std::tanh to establish the platform's libm accuracy.
TEST(LibmBaseline, TanhF32) {
  auto report = TestAccuracyF32(
      "std::tanh", kGoldenTanh,
      std::function<float(float)>([](float x) { return std::tanh(x); }));
  LogReport(report);
  // Don't assert budget — this is informational.
}

