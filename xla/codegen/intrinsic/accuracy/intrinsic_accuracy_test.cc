// Systematic accuracy tests for XLA intrinsics against golden baselines.
//
// These tests measure the ULP error of each intrinsic implementation across
// ~200 domain-spanning reference points (generated by mpmath at 50-digit
// precision). The goals are:
//
// 1. Pin the current accuracy profile of each intrinsic.
// 2. Detect regressions when implementations change.
// 3. Provide side-by-side comparison data when migrating to Eigen-generated
//    intrinsics.
//
// Each test reports: max ULP error, mean ULP error, p99, and worst-case input.

